export default function HeroSection({ onScrollDown }) {
    const t = useTranslations('landing.hero');
    const mapRef = useRef(null);

    useEffect(() => {
        if (typeof window === 'undefined') return;
        const L = require('leaflet');
        window.L = L;
        require('leaflet.heat');

        const center = [24.554285272299817, 42.81154938863353];

        const map = L.map(mapRef.current, {
            zoomControl: false,
            attributionControl: false,
            dragging: false,
            scrollWheelZoom: false,
        }).setView(center, window.innerWidth < 768 ? 6 : 7);

        L.tileLayer(
            'https://{s}.basemaps.cartocdn.com/dark_nolabels/{z}/{x}/{y}{r}.png',
            { subdomains: 'abcd', maxZoom: 18 }
        ).addTo(map);

        // Decide which polygons to show on small screens
        const polygonsToShow = window.innerWidth < 768
            ? [QASSIM_POINTS]
            : [QASSIM_POINTS, MAKKAH_POINTS, TABUK_POINTS];

        polygonsToShow.forEach((coords) => {
            L.polygon(coords, {
                color: '#22c55e',
                weight: 2,
                fillColor: '#22c55e',
                fillOpacity: 0.25,
                className: 'hero-polygon',
            }).addTo(map);
        });

        // Generate heatmap points for Riyadh and Eastern Province
        const heatmapPoints = [];
        
        const riyadhHotspots = [
            { lat: 24.711, lng: 46.674, weight: 1.0 }, // Kingdom Center
            { lat: 24.761, lng: 46.640, weight: 0.9 }, // KAFD
            { lat: 24.846, lng: 46.732, weight: 0.8 }, // Airport Area
            { lat: 24.682, lng: 46.623, weight: 0.8 }, // DQ
            { lat: 24.630, lng: 46.710, weight: 0.7 }, // South Riyadh
            { lat: 24.734, lng: 46.575, weight: 0.6 }  // Diriyah
        ];

        const easternHotspots = [
            { lat: 26.420, lng: 50.088, weight: 1.0 }, // Dammam
            { lat: 26.280, lng: 50.208, weight: 0.9 }, // Khobar
            { lat: 26.310, lng: 50.132, weight: 0.8 }, // Dhahran
            { lat: 26.392, lng: 50.147, weight: 0.7 }, // Saihat
            { lat: 26.549, lng: 49.980, weight: 0.6 }  // Qatif
        ];

        // Generate random points around hotspots to create a dense heatmap effect
        [...riyadhHotspots, ...easternHotspots].forEach(spot => {
            // Keep point count low (e.g. 300) to prevent lag, but spread them wide
            const numPoints = Math.floor(spot.weight * 300);
            for (let i = 0; i < numPoints; i++) {
                // Mix of close points and wide spread points (up to 1.5 degrees, ~150km)
                const spread = Math.random() > 0.6 ? 1.5 : 0.4; 
                const latOffset = (Math.random() - 0.5) * spread;
                const lngOffset = (Math.random() - 0.5) * spread;
                heatmapPoints.push([spot.lat + latOffset, spot.lng + lngOffset, Math.random() * spot.weight]);
            }
        });

        // Add the heat layer
        L.heatLayer(heatmapPoints, {
            radius: 45,      // Increased radius to cover more area per point
            blur: 35,        // Increased blur to blend sparse points into a smooth heatmap
            maxZoom: 10,
            gradient: {
                0.4: 'blue',
                0.6: 'cyan',
                0.7: 'lime',
                0.8: 'yellow',
                1.0: 'red'
            }
        }).addTo(map);

        // Optional parallax on large screens
        if (window.innerWidth >= 768) {
            const handleMouseMove = (e) => {
                const x = (e.clientX / window.innerWidth - 0.5) * 1.5;
                const y = (e.clientY / window.innerHeight - 0.5) * 1.5;

                map.panTo([center[0] - y, center[1] + x], {
                    animate: true,
                    duration: 0.4,
                });
            };

            window.addEventListener('mousemove', handleMouseMove);

            return () => {
                window.removeEventListener('mousemove', handleMouseMove);
                map.remove();
            };
        }

        return () => map.remove();
    }, []);

    return (
        <section className="relative w-screen h-screen flex items-center justify-center px-6 sm:px-10 bg-[#262626]">

            {/* Map */}
            <div
                ref={mapRef}
                className="absolute inset-0 z-0 pointer-events-none"
            />

            {/* Overlay */}
            <div className="absolute inset-0 bg-black/30 z-10" />

            {/* Content */}
            <div className="relative z-20 text-center max-w-5xl mx-auto">
                <h1 className="
                    text-2xl sm:text-4xl lg:text-6xl rtl:lg:text-7xl
                    font-bold leading-12 md:leading-24 rtl:lg:leading-32 text-white capitalize
                ">
                    {t.rich('title', {
                        line1: (chunks) => <div className="whitespace-nowrap">{chunks}</div>,
                        line2: (chunks) => <div className="whitespace-nowrap">{chunks}</div>,
                        geo: (chunks) => <span className="bg-earthy-green px-1">{chunks}</span>,
                        maps: (chunks) => <span className="bg-[#2C3580] px-1">{chunks}</span>,
                    })}
                </h1>

                <p className="
                    mt-6 text-sm md:text-lg
                    text-gray-300 font-medium mx-auto
                ">
                    {t('description')}
                </p>

                <div className="mt-8 grid grid-cols-1 sm:grid-cols-2 gap-4 w-full mx-auto md:max-w-md">
                    <Link href="/dashboard/projects" className="w-full">
                        <Button
                            size="lg"
                            className="w-full bg-primary text-white text-base sm:text-lg py-6 sm:py-8 rounded-md shadow-xl hover:bg-primary/90 transition-all"
                        >
                            {t('tryNow')}
                        </Button>
                    </Link>
                    <Button
                        onClick={onScrollDown}
                        variant="secondary"
                        className="w-full text-base sm:text-lg py-6 sm:py-8 rounded-md"
                    >
                        {t('exploreMore')}
                    </Button>
                </div>
            </div>

            {/* Scroll Indicator */}
            <div className="absolute bottom-6 sm:bottom-10 left-1/2 -translate-x-1/2 z-30">
                <button
                    onClick={onScrollDown}
                    className="flex flex-col items-center text-white/80 hover:text-white transition"
                >
                    <span className="text-xs sm:text-sm mb-1 tracking-wide">{t('scroll')}</span>
                    <ChevronDown className="w-5 h-5 sm:w-6 sm:h-6 animate-bounce" />
                </button>
            </div>
        </section>
    );
}